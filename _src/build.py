def plain(fragment):
    """HTML fragment to plain text for structured data."""
    t = re.sub(r"</li>", "; ", fragment)
    t = re.sub(r"</p>", " ", t)
    t = re.sub(r";\s*</ul>", ". ", t)
    t = re.sub(r"<[^>]+>", "", t)
    return re.sub(r"\s+", " ", html.unescape(t)).strip()


